	<h1 class="mb-4 text-3xl font-bold">Tentang SIH3 MSBL</h1>
	<p>
		Portal SIH3 adalah sebuah platform yang menyediakan informasi terkait Sistem Informasi Hidro
		Meteorologi, Hidrologi, dan HidroGeologi. Portal ini bertujuan untuk memberikan akses mudah dan
		cepat kepada masyarakat, peneliti, dan pihak terkait lainnya untuk memperoleh data dan informasi
		yang akurat mengenai kondisi hidrometeorologi, hidrologi, dan hidrogeologi di wilayah tertentu.
		Dengan adanya portal ini, diharapkan dapat meningkatkan kesadaran dan pemahaman masyarakat
		terhadap pentingnya pengelolaan sumber daya air serta mitigasi risiko bencana terkait cuaca dan
		hidrologi.
	</p>
